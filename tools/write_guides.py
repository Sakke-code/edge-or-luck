"""Write the mini guides to docs/guides/ for reading on GitHub.

    python tools/write_guides.py

The sources in src/edgeorluck/guides hold {{numbers}} that the site fills in
from the validation run; these copies have them filled in, and the site's links
point at the repository. A test fails when they are out of date.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from edgeorluck.web import guides  # noqa: E402

OUT = ROOT / "docs" / "guides"


def expected() -> dict:
    every = guides.load()
    files = {f"{g.slug}.md": g.for_github() for g in every}
    lines = ["<!-- Generated by tools/write_guides.py. -->", "# Mini guides", "",
             "Short reads on testing a trading idea without fooling yourself. The web page serves them at `/guides`.",
             ""]
    for key, label in guides.GROUPS.items():
        lines += [f"## {label}", ""]
        lines += [f"- [{g.title}]({g.slug}.md): {g.summary}" for g in every if g.group == key]
        lines.append("")
    files["README.md"] = "\n".join(lines)
    return files


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    files = expected()
    for old in OUT.glob("*.md"):
        if old.name not in files:
            old.unlink()
    for name, text in files.items():
        (OUT / name).write_text(text, encoding="utf-8", newline="\n")
        print(OUT / name)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
