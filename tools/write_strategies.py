"""Popular strategies, judged: compute data/strategies.json and its GitHub copy docs/strategies.md.

    python tools/write_strategies.py          # needs internet: a handful of price requests

Run it before a release (like tools/validate.py). The site and the API only read the saved file.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from edgeorluck.web import strategies  # noqa: E402


def main() -> int:
    data = strategies.compute()
    strategies.DATA.write_text(json.dumps(data, indent=1, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
    md = strategies.markdown(data).replace("](/", "](https://github.com/Sakke-code/edge-or-luck/blob/main/")
    (ROOT / "docs" / "strategies.md").write_text("<!-- Generated by tools/write_strategies.py. -->\n" + md,
                                                 encoding="utf-8", newline="\n")
    for s in data["strategies"]:
        print(f"{s['title']:30s} {strategies.summary(data, s)}")
    print(f"wrote {strategies.DATA.relative_to(ROOT)} and docs/strategies.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
